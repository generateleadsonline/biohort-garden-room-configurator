# Builds src/pdf-assets.js: Poppins (subset to the characters the PDF uses) and the logo, as
# base64 for jsPDF. Run after changing fonts or the logo: python3 tools/build-pdf-assets.py
import base64, io, os
from fontTools import subset
from fontTools.ttLib import TTFont
chars = ''.join(chr(c) for c in range(32, 127)) + '£–—’‘“”•·²×é°½®äöüÄÖÜß€→'
out = {}
for key, name in [('regular', 'Poppins-Regular.ttf'), ('semibold', 'Poppins-SemiBold.ttf')]:
    f = TTFont(os.path.join('tools/fonts', name))
    s = subset.Subsetter(subset.Options()); s.populate(text=chars); s.subset(f)
    buf = io.BytesIO(); f.save(buf); out[key] = base64.b64encode(buf.getvalue()).decode()
logo = base64.b64encode(open('public/assets/logo-pdf.jpg', 'rb').read()).decode()
with open('src/pdf-assets.js', 'w') as fh:
    fh.write('// Generated by tools/build-pdf-assets.py: Poppins subset (OFL) and the Biohort logo (rasterised from their own SVG, public/assets/biohort-logo.svg).\n')
    fh.write('export const PDF_FONTS = %s;\n' % ('{' + ', '.join(f'{k}: "{v}"' for k, v in out.items()) + '}'))
    fh.write('export const PDF_LOGO = "data:image/jpeg;base64,%s";\n' % logo)
print({k: len(v) for k, v in out.items()}, len(logo))
